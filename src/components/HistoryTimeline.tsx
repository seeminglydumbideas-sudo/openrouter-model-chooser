import React, { useState } from 'react';
import { CalendarClock, Pause, Play, SkipForward } from 'lucide-react';
import type { DaySummary } from '../services/history';

// Changes-per-day histogram under the 2D Matrix, with a day slider aligned on
// the bars. Each day's bar stacks what changed since the previous recorded day
// (added, rescored, repriced models); removed models hang below the baseline.
// The first day has no predecessor, so it shows no changes.

export interface TimelineEntry extends DaySummary {
  // Today's live fetch when the server has no record for it yet.
  unsaved?: boolean;
}

interface HistoryTimelineProps {
  entries: TimelineEntry[];
  selectedIndex: number;
  onSelect: (index: number) => void;
  isPlaying: boolean;
  onTogglePlay: () => void;
  isLoadingDay: boolean;
}

const SERIES = [
  { key: 'added', label: 'Added', color: '#059669' },
  { key: 'rescored', label: 'Rescored', color: '#6366f1' },
  { key: 'repriced', label: 'Repriced', color: '#d97706' },
] as const;
const REMOVED = { label: 'Removed', color: '#f43f5e' };

const UP_HEIGHT = 72; // px above the baseline
const DOWN_HEIGHT = 22; // px below it, for removals
const THUMB = 16; // px, matches .timeline-range thumb in index.css

const formatDate = (date: string) =>
  new Date(`${date}T00:00:00Z`).toLocaleDateString(undefined, { month: 'short', day: 'numeric', timeZone: 'UTC' });

export const HistoryTimeline: React.FC<HistoryTimelineProps> = ({
  entries,
  selectedIndex,
  onSelect,
  isPlaying,
  onTogglePlay,
  isLoadingDay,
}) => {
  const [hoverIndex, setHoverIndex] = useState<number | null>(null);
  const n = entries.length;
  const selected = entries[selectedIndex];
  const isLatest = selectedIndex === n - 1;

  const maxUp = Math.max(1, ...entries.map(e => e.added + e.rescored + e.repriced));
  const maxDown = Math.max(1, ...entries.map(e => e.removed));
  // Shared scale above and below so a removal reads as big as an addition.
  const pxPerModel = Math.min(UP_HEIGHT / maxUp, DOWN_HEIGHT / maxDown);

  const tooltipIndex = hoverIndex ?? null;
  const tip = tooltipIndex !== null ? entries[tooltipIndex] : null;

  return (
    <div className="mt-4 flex flex-col gap-2 border-t border-slate-800 pt-4">
      {/* Header: selected day + controls + legend */}
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex items-center gap-2 text-xs">
          <CalendarClock className="h-4 w-4 text-cyan-400" />
          <span className="font-bold uppercase tracking-wider text-white">Timeline</span>
          <span className="font-semibold text-cyan-300">{selected ? formatDate(selected.date) : '—'}</span>
          {selected && <span className="text-slate-400">· {selected.count} models</span>}
          {selected?.synthetic && (
            <span className="rounded border border-slate-600 bg-slate-800 px-1.5 py-0.5 text-[10px] font-semibold text-slate-300" title="Generated by scripts/generate-fake-history.ts, not a real fetch">
              synthetic
            </span>
          )}
          {isLoadingDay && <span className="text-slate-500">loading…</span>}
        </div>

        <div className="flex flex-wrap items-center gap-3">
          <div className="flex items-center gap-3 text-[11px] text-slate-400">
            {[...SERIES, REMOVED].map(s => (
              <span key={s.label} className="flex items-center gap-1">
                <span className="h-2 w-2 rounded-sm" style={{ backgroundColor: s.color }} />
                {s.label}
              </span>
            ))}
          </div>
          <button
            onClick={onTogglePlay}
            disabled={n < 2}
            className="flex items-center gap-1 rounded-md border border-slate-700 bg-slate-900 px-2 py-1 text-[11px] font-semibold text-slate-300 hover:text-white disabled:opacity-40"
            title={isPlaying ? 'Pause' : 'Replay every day up to the latest'}
          >
            {isPlaying ? <Pause className="h-3 w-3" /> : <Play className="h-3 w-3" />}
            {isPlaying ? 'Pause' : 'Play'}
          </button>
          <button
            onClick={() => onSelect(n - 1)}
            disabled={isLatest}
            className="flex items-center gap-1 rounded-md border border-cyan-500/40 bg-cyan-500/10 px-2 py-1 text-[11px] font-semibold text-cyan-300 hover:bg-cyan-500/20 disabled:border-slate-800 disabled:bg-slate-900 disabled:text-slate-500"
          >
            <SkipForward className="h-3 w-3" />
            Latest
          </button>
        </div>
      </div>

      {/* Histogram */}
      <div className="relative" onMouseLeave={() => setHoverIndex(null)}>
        <div className="flex w-full" style={{ height: UP_HEIGHT + DOWN_HEIGHT + 1 }}>
          {entries.map((e, i) => {
            const isSelected = i === selectedIndex;
            return (
              <button
                key={e.date}
                onClick={() => onSelect(i)}
                onMouseEnter={() => setHoverIndex(i)}
                aria-label={`${e.date}: ${e.added} added, ${e.rescored} rescored, ${e.repriced} repriced, ${e.removed} removed`}
                className={`flex flex-1 flex-col items-stretch px-px ${isSelected ? 'bg-cyan-500/15' : hoverIndex === i ? 'bg-slate-700/30' : ''}`}
              >
                <div className="flex flex-col-reverse justify-start gap-[2px] w-full" style={{ height: UP_HEIGHT }}>
                  {SERIES.map((s, si) => {
                    const v = e[s.key];
                    if (!v) return null;
                    const isTop = SERIES.slice(si + 1).every(o => !e[o.key]);
                    return (
                      <div
                        key={s.key}
                        style={{ height: Math.max(2, v * pxPerModel), backgroundColor: s.color }}
                        className={isTop ? 'rounded-t' : ''}
                      />
                    );
                  })}
                </div>
                <div className="h-px w-full bg-slate-600" />
                <div className="w-full" style={{ height: DOWN_HEIGHT }}>
                  {e.removed > 0 && (
                    <div className="rounded-b" style={{ height: Math.max(2, e.removed * pxPerModel), backgroundColor: REMOVED.color }} />
                  )}
                </div>
              </button>
            );
          })}
        </div>

        {tip && tooltipIndex !== null && (
          <div
            className="pointer-events-none absolute bottom-full z-10 mb-2 w-max -translate-x-1/2 rounded-lg border border-slate-700/80 bg-slate-950/95 p-2 text-[11px] shadow-2xl"
            style={{ left: `clamp(70px, ${((tooltipIndex + 0.5) / n) * 100}%, calc(100% - 70px))` }}
          >
            <div className="mb-1 font-bold text-white">
              {formatDate(tip.date)} · {tip.count} models
              {tip.synthetic && <span className="ml-1 font-normal text-slate-400">(synthetic)</span>}
              {tip.unsaved && <span className="ml-1 font-normal text-slate-400">(live, not saved)</span>}
            </div>
            {tooltipIndex === 0 ? (
              <div className="text-slate-400">First record — nothing to compare with</div>
            ) : (
              [...SERIES.map(s => ({ ...s, v: tip[s.key] })), { ...REMOVED, key: 'removed', v: tip.removed }].map(s => (
                <div key={s.label} className="flex items-center justify-between gap-4 text-slate-300">
                  <span className="flex items-center gap-1">
                    <span className="h-2 w-2 rounded-sm" style={{ backgroundColor: s.color }} />
                    {s.label}
                  </span>
                  <span className="font-semibold text-white">{s.v}</span>
                </div>
              ))
            )}
          </div>
        )}
      </div>

      {/* Slider, inset so its thumb centre sits on each bar's centre */}
      <input
        type="range"
        min={0}
        max={Math.max(0, n - 1)}
        step={1}
        value={selectedIndex}
        onChange={(ev) => onSelect(Number(ev.target.value))}
        disabled={n < 2}
        aria-label="Displayed day"
        className="timeline-range"
        style={{
          marginLeft: `calc(${50 / n}% - ${THUMB / 2}px)`,
          width: `calc(${100 - 100 / n}% + ${THUMB}px)`,
        }}
      />
      <div className="flex justify-between text-[10px] text-slate-500">
        <span>{entries[0] && formatDate(entries[0].date)}</span>
        <span>{n} day{n === 1 ? '' : 's'} recorded</span>
        <span>{entries[n - 1] && formatDate(entries[n - 1].date)}</span>
      </div>
    </div>
  );
};
